"""Honest, reproducible evaluation of TrustNet's detection layers.

Usage (from backend/):
    python evaluate.py                       # synthetic part (B) only; writes ../docs/EVALUATION.{json,md}
    python evaluate.py --real-data PATH.csv  # also part (A) on the held-out latest period of the RBA data

Part B uses fictional generated users (about 20 users, 21 days of normal behaviour, about 40 attack
sessions in four scenarios incl. harder slow-and-low and mimicry cases). Time split: first 14 days train
(normal behaviour only), last 7 days are held out. Everything is seeded, so one seed always gives
identical output.

What "full pipeline" means HERE: an evaluation-level fusion of the rules baseline, the Isolation Forest,
device trust, a known-bad IP feed and incident correlation, with fixed point weights chosen BEFORE
looking at results. It is not a call into the live FastAPI risk engine. All data is generated by this
file's author; the generator's difficulty shapes the numbers. Nothing here estimates real-world accuracy.
"""
from __future__ import annotations

import argparse
import contextlib
import io
import json
import os
from statistics import mean, pstdev

import numpy as np

from models.optimized_models import OptimizedAnomalyDetector

FEATURES = ["session_duration", "data_volume", "api_calls", "geo_distance", "login_hour"]
SEEDS = [11, 12, 13, 14, 15]
N_USERS, DAYS, TRAIN_DAYS = 20, 21, 14
SCENARIOS = ["stolen_credentials", "insider_exfiltration", "slow_and_low", "mimicry"]
ATTACKS_PER_SCENARIO = 4  # campaigns; several sessions each -> about 40 attack sessions in total
INCIDENT_WINDOW_MIN = 24 * 60

# Fixed fusion weights (points). Chosen before running; not tuned on results.
POINTS = {"rules": 40, "model": 30, "untrusted_device": 20, "known_bad_ip": 40}
ALERT_AT = 50


# ---------------------------------------------------------------- data generation
def generate(seed: int) -> dict:
    rng = np.random.default_rng(seed)
    users = []
    for u in range(N_USERS):
        users.append({
            "id": u,
            "hour": rng.uniform(8, 13), "hour_sd": rng.uniform(1.0, 2.0),
            "dur": rng.uniform(3.8, 5.2), "vol": rng.uniform(110, 190), "api": rng.uniform(150, 250),
            "geo": rng.uniform(40, 60),
        })
    rows = []

    def add(u, minute, hour, dur, vol, api, geo, trusted, bad_ip, label, scenario, attack_id):
        rows.append({"user": u["id"], "minute": float(minute), "session_duration": float(dur), "data_volume": float(vol),
                     "api_calls": float(api), "geo_distance": float(geo), "login_hour": float(np.clip(hour, 0, 23.99)),
                     "device_trusted": bool(trusted), "ip_known_bad": bool(bad_ip), "label": int(label),
                     "scenario": scenario, "attack_id": attack_id})

    for u in users:
        for day in range(DAYS):
            for _ in range(int(rng.integers(1, 4))):
                hour = rng.normal(u["hour"], u["hour_sd"])
                if rng.random() < 0.03:                       # occasional late-night work
                    hour = rng.uniform(20, 23.5)
                geo = rng.normal(u["geo"], 8) if rng.random() > 0.015 else rng.uniform(85, 130)  # rare travel
                add(u, day * 1440 + hour * 60, hour, rng.normal(u["dur"], 0.8), rng.normal(u["vol"], 30),
                    rng.normal(u["api"], 40), geo, rng.random() > 0.03, False, 0, "normal", None)

    attack_id = 0
    first_test_day = TRAIN_DAYS
    for scenario in SCENARIOS:
        for _ in range(ATTACKS_PER_SCENARIO):
            u = users[int(rng.integers(0, N_USERS))]
            start_day = int(rng.integers(first_test_day, DAYS - 2))
            n = {"stolen_credentials": int(rng.integers(2, 4)), "insider_exfiltration": int(rng.integers(2, 4)),
                 "slow_and_low": int(rng.integers(3, 5)), "mimicry": int(rng.integers(2, 4))}[scenario]
            for k in range(n):
                if scenario == "stolen_credentials":
                    hour = rng.uniform(0, 5); geo = rng.uniform(90, 140); vol = rng.normal(u["vol"] * 1.8, 40)
                    dur = rng.normal(u["dur"] * 1.6, 0.8); api = rng.normal(u["api"] * 1.8, 50)
                    trusted, bad = False, rng.random() < 0.3
                    day = start_day
                elif scenario == "insider_exfiltration":
                    hour = rng.normal(u["hour"], u["hour_sd"]); geo = rng.normal(u["geo"], 8)
                    vol = rng.uniform(260, 500); api = rng.uniform(300, 480); dur = rng.normal(u["dur"] * 1.5, 0.8)
                    trusted, bad = True, False
                    day = start_day
                elif scenario == "slow_and_low":
                    hour = rng.normal(u["hour"], u["hour_sd"]); geo = rng.normal(u["geo"], 8)
                    vol = rng.normal(u["vol"] + 1.5 * 30, 25); api = rng.normal(u["api"] + 1.2 * 40, 30)
                    dur = rng.normal(u["dur"] + 0.8, 0.6)
                    trusted, bad = rng.random() < 0.5, False
                    day = min(DAYS - 1, start_day + k)
                else:  # mimicry: matches the user's normal hours and location
                    hour = rng.normal(u["hour"], u["hour_sd"] * 0.7); geo = rng.normal(u["geo"], 6)
                    vol = rng.normal(u["vol"] * 1.15, 25); api = rng.normal(u["api"] * 1.2, 35)
                    dur = rng.normal(u["dur"], 0.6)
                    trusted, bad = rng.random() < 0.3, rng.random() < 0.15
                    day = start_day
                add(u, day * 1440 + hour * 60 + k * 7, hour, dur, vol, api, geo, trusted, bad, 1, scenario, attack_id)
            attack_id += 1
    rows.sort(key=lambda r: (r["minute"], r["user"]))
    return {"rows": rows}


def split(rows: list[dict]) -> tuple[list[dict], list[dict]]:
    cut = TRAIN_DAYS * 1440
    train = [r for r in rows if r["minute"] < cut]
    test = [r for r in rows if r["minute"] >= cut]
    return train, test


def matrix(rows: list[dict]) -> np.ndarray:
    return np.array([[r[f] for f in FEATURES] for r in rows], dtype=float)


# ---------------------------------------------------------------- detectors
def rules_only(samples: np.ndarray) -> np.ndarray:
    """Fixed global thresholds, same rule shape as evaluate_synthetic.py. Not tuned to this generator."""
    return ((samples[:, 0] > 7.0) | (samples[:, 1] > 260) | (samples[:, 2] > 330)
            | (samples[:, 3] > 82) | (samples[:, 4] > 18.5)).astype(int)


def model_flags(train: list[dict], test: list[dict]) -> np.ndarray:
    detector = OptimizedAnomalyDetector()
    normal = [r for r in train if r["label"] == 0]
    with contextlib.redirect_stdout(io.StringIO()):
        result = detector.train(X=matrix(normal), feature_names=list(FEATURES))
    if result.get("status") != "success":
        raise RuntimeError(result.get("message"))
    preds, _ = detector.predict(matrix(test))
    return (preds == -1).astype(int)


def fused_alerts(test, rules, model, *, known_bad=True, device_trust=True) -> np.ndarray:
    pts = np.zeros(len(test))
    pts += POINTS["rules"] * rules + POINTS["model"] * model
    if device_trust:
        pts += POINTS["untrusted_device"] * np.array([not r["device_trusted"] for r in test])
    if known_bad:
        pts += POINTS["known_bad_ip"] * np.array([r["ip_known_bad"] for r in test])
    return (pts >= ALERT_AT).astype(int)


# ---------------------------------------------------------------- metrics
def classification_metrics(labels: np.ndarray, alerts: np.ndarray) -> dict:
    tp = int(((labels == 1) & (alerts == 1)).sum()); fp = int(((labels == 0) & (alerts == 1)).sum())
    fn = int(((labels == 1) & (alerts == 0)).sum()); tn = int(((labels == 0) & (alerts == 0)).sum())
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return {"precision": precision, "recall": recall, "f1": f1, "false_positive_rate": fp / (fp + tn) if fp + tn else 0.0,
            "tp": tp, "fp": fp, "fn": fn, "tn": tn}


def correlate(test: list[dict], alerts: np.ndarray, window: int = INCIDENT_WINDOW_MIN) -> int:
    """Group alerts of the same user that fall within `window` minutes of the incident's first alert."""
    open_incident: dict[int, float] = {}
    count = 0
    for row, alerted in zip(test, alerts):
        if not alerted:
            continue
        start = open_incident.get(row["user"])
        if start is None or row["minute"] - start > window:
            open_incident[row["user"]] = row["minute"]
            count += 1
    return count


def response_times(test: list[dict], alerts: np.ndarray) -> tuple[list[float], int, int]:
    """Minutes from an attack campaign's first session to its first alerted session (detected only)."""
    first, first_alert = {}, {}
    for row, alerted in zip(test, alerts):
        a = row["attack_id"]
        if a is None:
            continue
        first.setdefault(a, row["minute"])
        if alerted and a not in first_alert:
            first_alert[a] = row["minute"]
    times = [first_alert[a] - first[a] for a in first_alert]
    return times, len(first_alert), len(first)


def evaluate_variant(test, alerts, correlation=True) -> dict:
    labels = np.array([r["label"] for r in test])
    out = classification_metrics(labels, alerts)
    times, detected, campaigns = response_times(test, alerts)
    out["mean_time_to_first_response_min"] = mean(times) if times else None
    out["campaigns_detected"], out["campaigns_total"] = detected, campaigns
    out["alerts"] = int(alerts.sum())
    out["incidents"] = correlate(test, alerts) if correlation else int(alerts.sum())
    return out


def per_scenario_recall(test, alerts) -> dict:
    result = {}
    for scenario in SCENARIOS:
        idx = [i for i, r in enumerate(test) if r["scenario"] == scenario]
        hit = sum(int(alerts[i]) for i in idx)
        result[scenario] = round(hit / len(idx), 4) if idx else None
    return result


def run_seed(seed: int) -> dict:
    data = generate(seed)
    train, test = split(data["rows"])
    X = matrix(test)
    rules = rules_only(X)
    model = model_flags(train, test)
    variants = {
        "rules_only_baseline": (rules, True),
        "isolation_forest_alone": (model, True),
        "full_pipeline": (fused_alerts(test, rules, model), True),
        "ablation_no_correlation": (fused_alerts(test, rules, model), False),
        "ablation_no_known_bad": (fused_alerts(test, rules, model, known_bad=False), True),
        "ablation_no_device_trust": (fused_alerts(test, rules, model, device_trust=False), True),
    }
    out = {name: evaluate_variant(test, alerts, corr) for name, (alerts, corr) in variants.items()}
    out["_recall_by_scenario"] = {name: per_scenario_recall(test, alerts) for name, (alerts, _) in variants.items()}
    out["_counts"] = {"train_rows": len(train), "test_rows": len(test),
                      "attack_sessions": int(sum(r["label"] for r in test)),
                      "attack_campaigns": len({r["attack_id"] for r in test if r["attack_id"] is not None})}
    return out


def aggregate(per_seed: list[dict]) -> dict:
    agg = {}
    for name in per_seed[0]:
        if name.startswith("_"):
            continue
        agg[name] = {}
        for metric in per_seed[0][name]:
            values = [s[name][metric] for s in per_seed if s[name][metric] is not None]
            if not values:
                agg[name][metric] = {"mean": None, "std": None, "n": 0}
                continue
            agg[name][metric] = {"mean": round(float(mean(values)), 4), "std": round(float(pstdev(values)), 4), "n": len(values)}
    return agg


# ---------------------------------------------------------------- real-data part (A)
def real_part(path: str) -> dict:
    from sklearn.metrics import average_precision_score, roc_auc_score
    from ml.data_loader import FEATURES as F, read_sample, time_split, to_features
    from ml.train_real import train

    feats = to_features(read_sample(path, sample_frac=0.05))
    detector, split_info, metrics, n_train = train(feats)
    _, test, _ = time_split(feats, 0.7)
    labels = test["label"].to_numpy()
    out = {"status": "ran", "data": "RBA public login dataset (sample)", "split": split_info, "model_metrics": metrics}
    if 0 < labels.sum() < len(labels):
        rule_score = ((test["geo_distance"] >= 100) | test["login_hour"].between(0, 5)).astype(float).to_numpy()
        out["rules_baseline"] = {"roc_auc": round(float(roc_auc_score(labels, rule_score)), 4),
                                 "average_precision": round(float(average_precision_score(labels, rule_score)), 4),
                                 "rule": "new country for the user, or login between 00:00 and 05:59 UTC"}
    else:
        out["note"] = "Test period holds one class; comparison not computable."
    return out


# ---------------------------------------------------------------- reporting
def build_report(real_path: str | None = None) -> dict:
    per_seed = [run_seed(s) for s in SEEDS]
    report = {
        "evaluation": "trustnet_detection_evaluation",
        "data_statement": {
            "part_B_synthetic": "ALL numbers in `synthetic` are from fictional generated users; they are not real-world accuracy.",
            "part_A_real": "Numbers in `real_data` (if present) come from one public dataset sample with a time-based split.",
        },
        "seeds": SEEDS,
        "design": {"users": N_USERS, "days": DAYS, "train_days": TRAIN_DAYS, "held_out_days": DAYS - TRAIN_DAYS,
                   "scenarios": SCENARIOS, "fusion_points": POINTS, "alert_at": ALERT_AT,
                   "incident_window_min": INCIDENT_WINDOW_MIN},
        "counts_per_seed": [s["_counts"] for s in per_seed],
        "synthetic": aggregate(per_seed),
        "recall_by_scenario_mean": {
            name: {sc: round(float(mean(s["_recall_by_scenario"][name][sc] for s in per_seed)), 4) for sc in SCENARIOS}
            for name in per_seed[0]["_recall_by_scenario"]},
    }
    if real_path:
        report["real_data"] = real_part(real_path)
    else:
        report["real_data"] = {"status": "blocked", "reason": "No dataset provided. Run: python evaluate.py --real-data ../data/raw/rba-dataset.csv"}
    return report


def _cell(m: dict, metric: str, pct=False) -> str:
    v = m[metric]
    if v["mean"] is None:
        return "n/a"
    return f"{v['mean']:.3f} ± {v['std']:.3f}"


def markdown(report: dict) -> str:
    s = report["synthetic"]
    lines = ["# Evaluation", "",
             "**Data statement.** Section B uses fictional generated users and attacks. It is not real-world accuracy. "
             "Section A uses a public dataset only if it was provided when this file was generated.", "",
             f"Seeds: {report['seeds']} (mean ± population std). Held out: last {report['design']['held_out_days']} of "
             f"{report['design']['days']} days; models trained on the first {report['design']['train_days']} days of normal behaviour.", "",
             "## B. Synthetic comparison", "",
             "| Variant | Precision | Recall | F1 | FPR | Mean min to first response | Alerts | Incidents | Campaigns detected |",
             "|---|---|---|---|---|---|---|---|---|"]
    for name, m in s.items():
        det = f"{m['campaigns_detected']['mean']:.1f} / {m['campaigns_total']['mean']:.0f}"
        lines.append(f"| {name} | {_cell(m,'precision')} | {_cell(m,'recall')} | {_cell(m,'f1')} | {_cell(m,'false_positive_rate')} | "
                     f"{_cell(m,'mean_time_to_first_response_min')} | {_cell(m,'alerts')} | {_cell(m,'incidents')} | {det} |")
    lines += ["", "Recall by scenario (mean over seeds):", "", "| Variant | " + " | ".join(SCENARIOS) + " |",
              "|---|" + "---|" * len(SCENARIOS)]
    for name, row in report["recall_by_scenario_mean"].items():
        lines.append(f"| {name} | " + " | ".join(f"{row[sc]:.2f}" for sc in SCENARIOS) + " |")
    real = report["real_data"]
    lines += ["", "## A. Real data", ""]
    if real.get("status") == "ran":
        lines += ["```json", json.dumps(real, indent=2), "```"]
    else:
        lines.append(f"Blocked: {real.get('reason')}")
    base, full, model = s["rules_only_baseline"], s["full_pipeline"], s["isolation_forest_alone"]
    winner = "the rules-only baseline" if base["f1"]["mean"] >= full["f1"]["mean"] else "the full pipeline"
    lines += ["", "## Reading these numbers honestly", "",
              f"On F1 in this synthetic setup, {winner} scores higher (baseline {base['f1']['mean']:.3f}, full pipeline "
              f"{full['f1']['mean']:.3f}, Isolation Forest alone {model['f1']['mean']:.3f}). The generator was written by the "
              "project author, so the margin depends on how hard the scenarios were made. The fusion weights were fixed in "
              "advance and are not tuned.", "",
              "Beyond raw accuracy the pipeline adds things this table does not score: plain-language reasons per score, "
              "correlation of repeated alerts into one incident (compare the Alerts and Incidents columns), bounded automatic "
              "response with human approval for irreversible actions, and an audit trail. If a baseline wins on F1, that "
              "is a fair result and is reported as such. Slow-and-low and mimicry rows show where every variant is weakest.", "",
              "Mean time to first response is computed only over attack campaigns that were detected at all, so a variant that "
              "detects fewer campaigns can look faster; read it together with the Campaigns detected column.", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--real-data")
    ap.add_argument("--out-dir", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs"))
    args = ap.parse_args(argv)
    report = build_report(args.real_data)
    os.makedirs(args.out_dir, exist_ok=True)
    with open(os.path.join(args.out_dir, "EVALUATION.json"), "w", encoding="utf-8") as h:
        json.dump(report, h, indent=2, sort_keys=True)
        h.write("\n")
    with open(os.path.join(args.out_dir, "EVALUATION.md"), "w", encoding="utf-8") as h:
        h.write(markdown(report))
    print(f"Wrote EVALUATION.json and EVALUATION.md to {os.path.abspath(args.out_dir)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
